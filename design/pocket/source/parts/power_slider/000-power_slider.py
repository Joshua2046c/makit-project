height=param("power_key_height_mm",2.4)
outer_w=param("power_key_width_mm",13.1)
arm_t=param("power_key_arm_mm",1.3)
arm_l=param("power_key_arm_length_mm",13.0)
tab_w=param("power_key_tab_width_mm",9.6)
tab_l=param("power_key_tab_length_mm",4.6)
tip_w=param("power_key_tip_width_mm",2.0)
forwards=param("power_key_tip_reach_mm",4.6)
arm_y=0.7
left=Pos(-(outer_w-arm_t)/2,arm_y)*RectangleRounded(arm_t,arm_l,0.45)
right=Pos((outer_w-arm_t)/2,arm_y)*RectangleRounded(arm_t,arm_l,0.45)
bridge=Pos(0,5.6)*RectangleRounded(outer_w,3.2,0.6)
tab=Pos(0,9.5)*RectangleRounded(tab_w,tab_l,0.6)
tip=Pos(0,forwards/2)*RectangleRounded(tip_w,forwards,0.35)
key=extrude(left+right+bridge+tab+tip,height)
key.color=srgb("#b2b36b")
publish("power_slider",key,"导向电源推键",material="petg")
