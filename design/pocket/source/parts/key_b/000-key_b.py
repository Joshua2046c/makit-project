diameter=param("key_b_diameter_mm",6.6)
height=param("key_b_height_mm",2.4)
socket_d=param("key_b_socket_diameter_mm",2.98)
socket_depth=param("key_b_socket_depth_mm",0.9)
edge_r=param("key_b_edge_radius_mm",0.45)
cap=Cylinder(diameter/2,height,align=(Align.CENTER,Align.CENTER,Align.MIN))
