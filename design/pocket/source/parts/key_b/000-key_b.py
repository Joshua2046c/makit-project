cap=chamfer(cap.edges().group_by(Axis.Z)[0],0.25)
cap-=Cylinder(socket_d/2,socket_depth,align=(Align.CENTER,Align.CENTER,Align.MIN))
cap.color=srgb("#e2c5ad")
publish("key_b",cap,"圆形功能键",material="petg")
fit("key_b","mainboard",kind="press_fit",budget_mm=0.15,reason="Prototype PETG cap socket on the original switch stem; calibrate the print before assembly")
