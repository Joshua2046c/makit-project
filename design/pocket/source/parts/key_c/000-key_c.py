diameter=param("key_c_diameter_mm",10.5)
height=param("key_c_height_mm",2.4)
socket_d=param("key_c_socket_diameter_mm",2.98)
socket_depth=param("key_c_socket_depth_mm",0.9)
edge_r=param("key_c_edge_radius_mm",0.45)
cap=Cylinder(diameter/2,height,align=(Align.CENTER,Align.CENTER,Align.MIN))
cap=fillet(cap.edges().group_by(Axis.Z)[-1],edge_r)
cap=chamfer(cap.edges().group_by(Axis.Z)[0],0.25)
cap-=Cylinder(socket_d/2,socket_depth,align=(Align.CENTER,Align.CENTER,Align.MIN))
cap.color=srgb("#b2b36b")
publish("key_c",cap,"绿色主功能键",material="petg")
fit("key_c","mainboard",kind="press_fit",budget_mm=0.15,reason="Prototype PETG cap socket on the original switch stem; calibrate the print before assembly")
